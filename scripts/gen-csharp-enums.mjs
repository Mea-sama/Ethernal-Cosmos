// Generates csharp-sdk/EthernalCosmos.Client/Models/Enums.cs and docs/enums.md from shared/src/types/enums.ts (the single source of truth).
// Usage: node scripts/gen-csharp-enums.mjs [--check]   (--check exits 1 when the file is outdated)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(resolve(root, 'shared/src/types/enums.ts'), 'utf8');
const target = resolve(root, 'csharp-sdk/EthernalCosmos.Client/Models/Enums.cs');
const docTarget = resolve(root, 'docs/enums.md');

// Where each enum shows up in the protocol/SDKs (documentation only)
const usedIn = {
  LobbyStatus: '`Lobby.status`',
  LobbyChangeReason: '`lobbyUpdated` (2nd argument), `lobby:updated` (game server)',
  LobbyServerStatus: '`Lobby.serverStatus`',
  ServerMode: '`createLobby` (`serverPreference.mode`)',
  ServerSupport: '`GameInfo.serverSupport`',
  LobbyAssignReason: '`lobby:assigned` (game server)',
  LobbyClosedReason: '`lobby:closed` (game server)',
  PlayerLeftReason: '`player:left` (game server)',
  SessionReplacedReason: '`session:replaced`',
  JoinRequestRejectReason: '`joinRequestRejected`',
  JoinRequestWithdrawReason: '`joinRequestWithdrawn`',
  DataVisibility: '`UserDataEntry.visibility`, `setUserData`',
  DataWriteScope: '`UserDataEntry.writeScope`',
  FriendRequestSource: '`FriendRequestInfo.source`',
  FriendRequestResult: '`friend:request` ack (`result`)',
  OwnPresenceStatus: '`SocialSettings.status`, `social:setSettings`',
  FriendPresenceStatus: '`friend:presence`',
  LobbyInviteCancelReason: '`lobby:inviteCancelled`',
  NotificationType: '`notification`, `SocialSettings.mutedNotificationTypes`',
  ErrorCode: '`errorDetail`, ack errors, REST error `code`',
};

const xml = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/`([^`]*)`/g, '<c>$1</c>');
const blocks = [...src.matchAll(/\/\*\* (.*?) \*\/\nexport const (\w+) = \{\n(.*?)\} as const;/gs)];
let out = `// <auto-generated>
// Generated from shared/src/types/enums.ts by scripts/gen-csharp-enums.mjs — do not edit by hand (npm run gen:enums).
// </auto-generated>
using System.Text.Json.Serialization;

namespace EthernalCosmos.Client.Models;
`;
for (const [, doc, name, body] of blocks) {
  const members = [...body.matchAll(/^\s+(\w+): '([^']+)',(?: \/\/ (.*))?$/gm)];
  const esc = xml(doc);
  out += `
/// <summary>${esc}</summary>
/// <remarks>Values not known to this SDK version deserialize to <c>Unknown</c>.</remarks>
[JsonConverter(typeof(WireEnumConverter<${name}>))]
public enum ${name}
{
    /// <summary>Value not known to this SDK version.</summary>
    Unknown = 0,
${members.map(([, key, wire, note]) => `    /// <summary>${note ? xml(note) : `Wire value <c>${wire}</c>.`}</summary>\n    [WireValue("${wire}")] ${key},`).join('\n')}
}
`;
}

let md = `# Wire enums

Every categorical value that travels over the wire (reasons, statuses, error codes, ...) is an enum. The wire values are plain strings,
so raw socket.io clients are unaffected; the ODKs expose them as typed enums.

- **Node.js**: const objects exported from \`@ethernal/client\` (value + type): \`LobbyChangeReason.ServerRebound === 'server_rebound'\`.
- **C#**: enums in \`EthernalCosmos.Client.Models\`: \`LobbyChangeReason.ServerRebound\`. Values unknown to an older SDK arrive as \`Unknown\` (the raw code stays available where relevant, e.g. \`EthernalException.Code\`).
- Source of truth: \`shared/src/types/enums.ts\`. This page and \`Enums.cs\` are generated: \`npm run gen:enums\` (CI checks they are current).

`;
for (const [, doc, name, body] of blocks) {
  const members = [...body.matchAll(/^\s+(\w+): '([^']+)',(?: \/\/ (.*))?$/gm)];
  md += `## ${name}\n\n${doc}\n\nUsed in: ${usedIn[name] ?? '-'}\n\n| Wire value | Node.js / C# member | Meaning |\n|---|---|---|\n${members.map(([, key, wire, note]) => `| \`${wire}\` | \`${name}.${key}\` | ${note ?? ''} |`).join('\n')}\n\n`;
}

const outputs = [[target, out], [docTarget, md.trimEnd() + '\n']];
if (process.argv.includes('--check')) {
  for (const [file, content] of outputs) {
    let current = '';
    try { current = readFileSync(file, 'utf8'); } catch { /* missing */ }
    if (current !== content) {
      console.error(`${file} is outdated — run: npm run gen:enums`);
      process.exit(1);
    }
  }
} else {
  for (const [file, content] of outputs) writeFileSync(file, content);
  console.log(`wrote Enums.cs and docs/enums.md (${blocks.length} enums)`);
}
