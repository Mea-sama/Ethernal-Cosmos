// Generates csharp-sdk/EthernalCosmos.Client/Models/Enums.cs from shared/src/types/enums.ts (the single source of truth).
// Usage: node scripts/gen-csharp-enums.mjs [--check]   (--check exits 1 when the file is outdated)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(resolve(root, 'shared/src/types/enums.ts'), 'utf8');
const target = resolve(root, 'csharp-sdk/EthernalCosmos.Client/Models/Enums.cs');

const blocks = [...src.matchAll(/\/\*\* (.*?) \*\/\nexport const (\w+) = \{\n(.*?)\} as const;/gs)];
let out = `// <auto-generated>
// Generated from shared/src/types/enums.ts by scripts/gen-csharp-enums.mjs — do not edit by hand (npm run gen:enums).
// </auto-generated>
using System.Text.Json.Serialization;

namespace EthernalCosmos.Client.Models;
`;
for (const [, doc, name, body] of blocks) {
  const members = [...body.matchAll(/^\s+(\w+): '([^']+)',$/gm)];
  const esc = doc.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  out += `
/// <summary>${esc}</summary>
/// <remarks>Values not known to this SDK version deserialize to <c>Unknown</c>.</remarks>
[JsonConverter(typeof(WireEnumConverter<${name}>))]
public enum ${name}
{
    /// <summary>Value not known to this SDK version.</summary>
    Unknown = 0,
${members.map(([, key, wire]) => `    [WireValue("${wire}")] ${key},`).join('\n')}
}
`;
}

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(target, 'utf8'); } catch { /* missing */ }
  if (current !== out) {
    console.error('Enums.cs is outdated — run: npm run gen:enums');
    process.exit(1);
  }
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target} (${blocks.length} enums)`);
}
